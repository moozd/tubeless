// The future set: invented true-color themes, none taken from a real
// screen or a published palette. Each pairs its own background with a
// hue family, so a theme changes the whole mood of the window (a
// rust-red Martian dusk, a pale clean room, a deep-sea abyss) and not
// only the text color. Palette order is the ANSI one: black, red,
// green, yellow, blue, magenta, cyan, white, then the 8 brights.


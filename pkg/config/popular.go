// popularThemeNames returns popularThemes' names, in order.
func popularThemeNames() []string {
	names := make([]string, len(popularThemes))
	for i, t := range popularThemes {
		names[i] = t.name
	}
	return names
}

// popularTheme looks name up in popularThemes.
func popularTheme(name string) (ThemeColors, bool) {
	for _, t := range popularThemes {
		if t.name == name {
			return t.colors(), true
		}
	}
	return ThemeColors{}, false
}

